import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'docs/api/json-rpc.md');
const check = process.argv.includes('--check');

const backendSource = 'packages/backend/src';
const methodMap = await read(`${backendSource}/codex/method-map.ts`);
const serverRequestMap = await read(`${backendSource}/codex/server-request-map.ts`);
const serverNotification = await read(`${backendSource}/codex/generated/ServerNotification.ts`);
const notificationController = await read(`${backendSource}/node/codex-surface-notifications-controller.ts`);
const schemaVersion = (await read(`${backendSource}/codex/schema-version.ts`)).match(
  /codexSchemaCliVersion\s*=\s*['"]([^'"]+)['"]/,
)?.[1]
  ?? 'unknown';
const productionFiles = (await sourceFiles(join(root, 'src'))).sort();
const productionSources = await Promise.all(productionFiles.map(async (path) => ({
  path,
  text: await readFile(path, 'utf8'),
})));

const clientMethods = matches(methodMap, /^  "([^"]+)":/gm);
const notifications = matches(serverNotification, /\{ "method": "([^"]+)"/g);
const serverRequests = matches(serverRequestMap, /^  "([^"]+)":/gm);
const ignoredNotificationBlock = notificationController.match(
  /case 'hook\/started':[\s\S]*?case 'windowsSandbox\/setupCompleted':\s*return;/,
)?.[0];
if (!ignoredNotificationBlock) {
  throw new Error('Could not locate the intentionally ignored notification block');
}
const ignoredNotifications = new Set(matches(ignoredNotificationBlock, /case '([^']+)':/g));
const handledNotifications = new Set(matches(notificationController, /case '([^']+)':/g));
const highLevelRequests = new Set([
  ...matches(productionSources.map(({ text }) => text).join('\n'), /\.request\(\s*['"]([^'"]+)['"]/g),
  'initialize',
]);
const handledServerRequests = new Set(
  matches(productionSources.map(({ text }) => text).join('\n'), /\.onServerRequest\(\s*['"]([^'"]+)['"]/g),
);
const policyBoundaryRequests = new Set([
  'account/chatgptAuthTokens/refresh',
  'attestation/generate',
]);

validateSubset('high-level request', highLevelRequests, clientMethods);
validateSubset('handled notification', handledNotifications, notifications);
validateSubset('ignored notification', ignoredNotifications, notifications);
validateSubset('handled server request', handledServerRequests, serverRequests);

const requestRows = clientMethods.map((method) => ({
  method,
  status: highLevelRequests.has(method) ? 'High-level SDK' : 'Typed client only',
  implementation: method === 'initialize'
    ? '`packages/backend/src/node/codex-surface-connection-controller.ts`'
    : highLevelRequests.has(method)
      ? implementationFiles(method, productionSources)
      : '—',
}));
const notificationRows = notifications.map((method) => ({
  method,
  status: ignoredNotifications.has(method)
    ? 'Intentionally ignored'
    : handledNotifications.has(method)
      ? 'High-level SDK'
      : 'Typed client only',
  implementation: handledNotifications.has(method)
    ? '`packages/backend/src/node/codex-surface-notifications-controller.ts`'
    : '—',
}));
const serverRequestRows = serverRequests.map((method) => ({
  method,
  status: policyBoundaryRequests.has(method)
    ? 'Host policy boundary'
    : handledServerRequests.has(method)
      ? 'High-level SDK'
      : 'Typed client only',
  implementation: handledServerRequests.has(method) ? implementationFiles(method, productionSources) : '—',
}));

const markdown = `<!-- Generated by scripts/generate-json-rpc-inventory.mjs. Do not edit by hand. -->
# JSON-RPC coverage inventory

This inventory tracks the checked-in \`${schemaVersion}\` app-server schema against
the SDK's high-level runtime. Every method remains available through the typed
\`CodexAppServerClient\`; the status indicates whether \`CodexSurface\` or another
high-level SDK runtime currently projects it.

Run \`npm run rpc:generate\` after regenerating the schema or changing protocol
handling. CI and local checks can use \`npm run rpc:check\` to detect drift.

## Status definitions

| Status | Meaning |
| --- | --- |
| **High-level SDK** | Used or handled by the Node surface/runtime. Applications normally use the product-shaped SDK API instead of this method directly. |
| **Host policy boundary** | The surface handles the request by explicitly rejecting it because the host must supply credentials or attestation policy. Advanced hosts can register a low-level handler. |
| **Intentionally ignored** | The notification is recognized exhaustively but currently produces no surface state or semantic event. |
| **Typed client only** | Fully typed at the low-level client boundary but not projected by the high-level runtime. This is the implementation backlog, not a protocol typing gap. |

## Summary

| Direction | Total | High-level | Policy boundary | Ignored | Typed only |
| --- | ---: | ---: | ---: | ---: | ---: |
${summaryRow('Client → app-server requests', requestRows)}
${summaryRow('App-server → client notifications', notificationRows)}
${summaryRow('App-server → client requests', serverRequestRows)}

## Client → app-server requests

${table(requestRows)}

## App-server → client notifications

${table(notificationRows)}

## App-server → client requests

${table(serverRequestRows)}

::: tip Reading the inventory
“Typed client only” is not necessarily a missing product feature. Many filesystem,
marketplace, process, and experimental methods intentionally remain low-level until
the SDK has a reusable, secure product contract for them.
:::
`;

if (check) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== markdown) {
    console.error('JSON-RPC inventory is stale. Run npm run rpc:generate.');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, markdown);
  console.log(`wrote ${relative(root, outputPath)}`);
}

async function read(path) {
  return readFile(join(root, path), 'utf8');
}

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      if (path === join(root, 'packages/backend/src/codex/generated')) continue;
      files.push(...await sourceFiles(path));
    } else if (entry.isFile() && entry.name.endsWith('.ts')) {
      files.push(path);
    }
  }
  return files;
}

function matches(text, pattern) {
  return [...text.matchAll(pattern)].map((match) => match[1]);
}

function validateSubset(label, values, available) {
  const known = new Set(available);
  const unknown = [...values].filter((value) => !known.has(value));
  if (unknown.length > 0) throw new Error(`Unknown ${label}s: ${unknown.join(', ')}`);
}

function implementationFiles(method, sources) {
  const files = sources
    .filter(({ text }) => text.includes(`'${method}'`) || text.includes(`"${method}"`))
    .map(({ path }) => relative(root, path))
    .filter((path) => !path.startsWith('packages/backend/src/codex/'))
    .sort();
  return files.length > 0 ? files.map((path) => `\`${path}\``).join('<br>') : 'built into typed client';
}

function summaryRow(label, rows) {
  const count = (status) => rows.filter((row) => row.status === status).length;
  return `| ${label} | ${rows.length} | ${count('High-level SDK')} | ${count('Host policy boundary')} | ${count('Intentionally ignored')} | ${count('Typed client only')} |`;
}

function table(rows) {
  return [
    '| Method | Status | Implementation |',
    '| --- | --- | --- |',
    ...rows.map(({ method, status, implementation }) => `| \`${method}\` | ${status} | ${implementation} |`),
  ].join('\n');
}
