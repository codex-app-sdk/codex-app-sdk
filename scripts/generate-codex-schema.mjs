import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const protocolDir = join(root, 'packages', 'backend', 'src', 'codex');
const generatedDir = join(protocolDir, 'generated');
const tempDir = mkdtempSync(join(tmpdir(), 'codex-app-sdk-schema-'));
const checkOnly = process.argv.includes('--check');

// Most generated FooParams types pair with FooResponse. These are the protocol's
// response type naming exceptions; they do not override values or runtime behavior.
const responseTypeNameExceptions = {
  'account/logout': 'LogoutAccountResponse',
  'account/rateLimits/read': 'GetAccountRateLimitsResponse',
  'account/usage/read': 'GetAccountTokenUsageResponse',
  'account/workspaceMessages/read': 'GetWorkspaceMessagesResponse',
  'config/batchWrite': 'ConfigWriteResponse',
  'config/mcpServer/reload': 'McpServerRefreshResponse',
  'config/value/write': 'ConfigWriteResponse',
  'externalAgentConfig/import/readHistories': 'ExternalAgentConfigImportHistoriesReadResponse',
};

try {
  execFileSync('codex', ['app-server', 'generate-ts', '--experimental', '--out', tempDir], {
    stdio: 'inherit',
  });

  const responseFiles = collectFiles(tempDir)
    .filter((file) => file.endsWith('Response.ts'));
  const responseByName = new Map(responseFiles.map((file) => [basename(file, '.ts'), file]));

  const methodMap = createMethodMap({
    generatedDir: tempDir,
    sourceFile: join(tempDir, 'ClientRequest.ts'),
    responseByName,
    responseTypeNameExceptions,
    exportedName: 'CodexAppServerMethodMap',
    requestTypeName: 'ClientRequest',
  });
  const serverRequestMap = createMethodMap({
    generatedDir: tempDir,
    sourceFile: join(tempDir, 'ServerRequest.ts'),
    responseByName,
    responseTypeNameExceptions: {},
    exportedName: 'CodexServerRequestMethodMap',
    requestTypeName: 'ServerRequest',
  });
  const cliVersion = execFileSync('codex', ['--version'], { encoding: 'utf8' }).trim();
  const schemaVersion = `// Generated by scripts/generate-codex-schema.mjs.\nexport const codexSchemaCliVersion = ${JSON.stringify(cliVersion)};\n`;

  if (checkOnly) {
    const changed = [
      ...differentGeneratedFiles(tempDir, generatedDir),
      ...differentTextFile(join(protocolDir, 'method-map.ts'), methodMap),
      ...differentTextFile(join(protocolDir, 'server-request-map.ts'), serverRequestMap),
      ...differentTextFile(join(protocolDir, 'schema-version.ts'), schemaVersion),
    ];
    if (changed.length > 0) {
      throw new Error(
        `Codex app-server schema is out of sync with ${cliVersion}:\n${changed.map((file) => `- ${file}`).join('\n')}\n`
        + 'Run npm run generate:schema and review the SDK compatibility changes.',
      );
    }
    process.stdout.write(`Codex app-server schema matches ${cliVersion}.\n`);
  } else {
    rmSync(generatedDir, { force: true, recursive: true });
    cpSync(tempDir, generatedDir, { recursive: true });
    writeFileSync(join(protocolDir, 'method-map.ts'), methodMap);
    writeFileSync(join(protocolDir, 'server-request-map.ts'), serverRequestMap);
    writeFileSync(join(protocolDir, 'schema-version.ts'), schemaVersion);
    process.stdout.write(`Generated Codex app-server schema from ${cliVersion}.\n`);
  }
} finally {
  rmSync(tempDir, { force: true, recursive: true });
}

function createMethodMap({
  generatedDir,
  sourceFile,
  responseByName,
  responseTypeNameExceptions,
  exportedName,
  requestTypeName,
}) {
  const source = readFileSync(sourceFile, 'utf8');
  const sourceAst = ts.createSourceFile(sourceFile, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const importPaths = parseImportPaths(sourceAst, sourceFile);
  const requestType = sourceAst.statements.find((statement) => (
    ts.isTypeAliasDeclaration(statement) && statement.name.text === requestTypeName
  ));
  if (!requestType) throw new Error(`No ${requestTypeName} type alias found in ${sourceFile}.`);
  const union = unwrapParenthesizedType(requestType.type);
  if (!ts.isUnionTypeNode(union)) {
    throw new Error(`${requestTypeName} must be a union type in ${sourceFile}.`);
  }
  const methods = [];

  for (const [index, rawMember] of union.types.entries()) {
    const member = unwrapParenthesizedType(rawMember);
    if (!ts.isTypeLiteralNode(member)) {
      throw new Error(`${requestTypeName} member ${index + 1} is not an object type: ${member.getText(sourceAst)}`);
    }
    const methodProperty = findProperty(member, 'method');
    const idProperty = findProperty(member, 'id');
    const paramsProperty = findProperty(member, 'params');
    const methodType = methodProperty && unwrapParenthesizedType(methodProperty.type);
    if (!methodType || !ts.isLiteralTypeNode(methodType) || !ts.isStringLiteral(methodType.literal)) {
      throw new Error(`${requestTypeName} member ${index + 1} has no string-literal method.`);
    }
    if (!idProperty || idProperty.type.getText(sourceAst) !== 'RequestId') {
      throw new Error(`${requestTypeName} method ${methodType.literal.text} has no RequestId id.`);
    }
    if (!paramsProperty) {
      throw new Error(`${requestTypeName} method ${methodType.literal.text} has no params property.`);
    }
    const method = methodType.literal.text;
    const params = paramsProperty.type.getText(sourceAst);
    const paramsTypes = referencedTypeNames(paramsProperty.type, sourceAst);
    const responseName = responseTypeNameExceptions[method]
      ?? paramsTypes
        .map((name) => name.endsWith('Params') ? `${name.slice(0, -'Params'.length)}Response` : '')
        .find((name) => responseByName.has(name))
      ?? responseNameFromMethod(method, responseByName);

    if (!responseName || !responseByName.has(responseName)) {
      throw new Error(`No generated response type found for ${method} (${params}).`);
    }

    methods.push({ method, params, paramsTypes, responseName });
  }
  const uniqueMethods = new Set(methods.map(({ method }) => method));
  if (methods.length !== union.types.length || uniqueMethods.size !== methods.length) {
    throw new Error(
      `${requestTypeName} completeness failure: parsed ${methods.length} entries, `
      + `${uniqueMethods.size} unique methods, from ${union.types.length} union members.`,
    );
  }

  const imports = new Map();
  for (const entry of methods) {
    for (const typeName of [...entry.paramsTypes, entry.responseName]) {
      const generatedPath = importPaths.get(typeName) ?? responseByName.get(typeName);
      if (!generatedPath) {
        throw new Error(`No generated import found for ${typeName}.`);
      }
      const relativePath = normalizeImportPath(join('generated', relative(generatedDir, generatedPath)).replace(/\.ts$/, ''));
      const names = imports.get(relativePath) ?? [];
      names.push(typeName);
      imports.set(relativePath, names);
    }
  }

  const lines = ['// Generated by scripts/generate-codex-schema.mjs. Do not edit by hand.'];
  for (const [path, names] of [...imports.entries()].sort(([left], [right]) => left.localeCompare(right))) {
    lines.push(`import type { ${[...new Set(names)].sort().join(', ')} } from ${JSON.stringify(path)};`);
  }
  lines.push('', `export interface ${exportedName} {`);
  for (const entry of methods) {
    lines.push(`  ${JSON.stringify(entry.method)}: { params: ${entry.params}; result: ${entry.responseName} };`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

function differentGeneratedFiles(candidateDir, committedDir) {
  const candidateFiles = new Map(collectFiles(candidateDir).map((file) => [relative(candidateDir, file), file]));
  const committedFiles = existsSync(committedDir)
    ? new Map(collectFiles(committedDir).map((file) => [relative(committedDir, file), file]))
    : new Map();
  const names = new Set([...candidateFiles.keys(), ...committedFiles.keys()]);
  return [...names]
    .filter((name) => {
      const candidate = candidateFiles.get(name);
      const committed = committedFiles.get(name);
      return !candidate || !committed || readFileSync(candidate, 'utf8') !== readFileSync(committed, 'utf8');
    })
    .sort()
    .map((name) => `packages/backend/src/codex/generated/${name}`);
}

function differentTextFile(path, expected) {
  return existsSync(path) && readFileSync(path, 'utf8') === expected
    ? []
    : [relative(root, path)];
}

function parseImportPaths(sourceAst, sourceFile) {
  const imports = new Map();
  for (const statement of sourceAst.statements) {
    if (!ts.isImportDeclaration(statement)
      || !ts.isStringLiteral(statement.moduleSpecifier)
      || !statement.importClause
      || !statement.importClause.namedBindings
      || !ts.isNamedImports(statement.importClause.namedBindings)) continue;
    const importedPath = resolve(dirname(sourceFile), `${statement.moduleSpecifier.text}.ts`);
    for (const element of statement.importClause.namedBindings.elements) {
      imports.set(element.name.text, importedPath);
    }
  }
  return imports;
}

function findProperty(member, name) {
  return member.members.find((candidate) => (
    ts.isPropertySignature(candidate) && propertyName(candidate.name) === name && candidate.type
  ));
}

function propertyName(name) {
  return name && (ts.isIdentifier(name) || ts.isStringLiteral(name)) ? name.text : undefined;
}

function unwrapParenthesizedType(node) {
  return ts.isParenthesizedTypeNode(node) ? unwrapParenthesizedType(node.type) : node;
}

function referencedTypeNames(rawNode, sourceAst) {
  const node = unwrapParenthesizedType(rawNode);
  if (ts.isUnionTypeNode(node)) {
    return node.types.flatMap((member) => referencedTypeNames(member, sourceAst));
  }
  if (ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)) {
    return node.typeName.text === 'undefined' ? [] : [node.typeName.text];
  }
  if ((ts.isLiteralTypeNode(node) && node.literal.kind === ts.SyntaxKind.NullKeyword)
    || node.kind === ts.SyntaxKind.UndefinedKeyword) return [];
  throw new Error(`Unsupported request params type: ${node.getText(sourceAst)}`);
}

function responseNameFromMethod(method, responseByName) {
  const pascal = method
    .split(/[\/_-]/)
    .filter(Boolean)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join('');
  const candidate = `${pascal}Response`;
  return responseByName.has(candidate) ? candidate : undefined;
}

function collectFiles(directory) {
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? collectFiles(path) : [path];
  });
}

function normalizeImportPath(path) {
  const normalized = path.split(sep).join('/');
  return normalized.startsWith('.') ? normalized : `./${normalized}`;
}
