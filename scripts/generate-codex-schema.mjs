import { execFileSync } from 'node:child_process';
import { cpSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const protocolDir = join(root, 'packages', 'backend', 'src', 'codex');
const generatedDir = join(protocolDir, 'generated');
const tempDir = mkdtempSync(join(tmpdir(), 'codex-app-sdk-schema-'));

// Most generated FooParams types pair with FooResponse. These are the protocol's
// response type naming exceptions; they do not override values or runtime behavior.
const responseTypeNameExceptions = {
  'account/logout': 'LogoutAccountResponse',
  'account/rateLimits/read': 'GetAccountRateLimitsResponse',
  'account/usage/read': 'GetAccountTokenUsageResponse',
  'account/workspaceMessages/read': 'GetWorkspaceMessagesResponse',
  'config/batchWrite': 'ConfigWriteResponse',
  'config/mcpServer/reload': 'McpServerRefreshResponse',
  'config/value/write': 'ConfigWriteResponse',
  'externalAgentConfig/import/readHistories': 'ExternalAgentConfigImportHistoriesReadResponse',
};

try {
  execFileSync('codex', ['app-server', 'generate-ts', '--experimental', '--out', tempDir], {
    stdio: 'inherit',
  });

  rmSync(generatedDir, { force: true, recursive: true });
  cpSync(tempDir, generatedDir, { recursive: true });

  const responseFiles = collectFiles(generatedDir)
    .filter((file) => file.endsWith('Response.ts'));
  const responseByName = new Map(responseFiles.map((file) => [basename(file, '.ts'), file]));

  const methodMap = createMethodMap({
    generatedDir,
    sourceFile: join(generatedDir, 'ClientRequest.ts'),
    responseByName,
    responseTypeNameExceptions,
    exportedName: 'CodexAppServerMethodMap',
  });
  writeFileSync(join(protocolDir, 'method-map.ts'), methodMap);

  const serverRequestMap = createMethodMap({
    generatedDir,
    sourceFile: join(generatedDir, 'ServerRequest.ts'),
    responseByName,
    responseTypeNameExceptions: {},
    exportedName: 'CodexServerRequestMethodMap',
  });
  writeFileSync(join(protocolDir, 'server-request-map.ts'), serverRequestMap);

  const cliVersion = execFileSync('codex', ['--version'], { encoding: 'utf8' }).trim();
  writeFileSync(
    join(protocolDir, 'schema-version.ts'),
    `// Generated by scripts/generate-codex-schema.mjs.\nexport const codexSchemaCliVersion = ${JSON.stringify(cliVersion)};\n`,
  );

  process.stdout.write(`Generated Codex app-server schema from ${cliVersion}.\n`);
} finally {
  rmSync(tempDir, { force: true, recursive: true });
}

function createMethodMap({ generatedDir, sourceFile, responseByName, responseTypeNameExceptions, exportedName }) {
  const source = readFileSync(sourceFile, 'utf8');
  const importPaths = parseImportPaths(source);
  const methods = [];
  const memberPattern = /\{ "method": "([^"]+)", id: RequestId, params: ([^,]+), \}/g;

  for (const match of source.matchAll(memberPattern)) {
    const method = match[1];
    const params = match[2].trim();
    const paramsTypes = params
      .split('|')
      .map((value) => value.trim())
      .filter((value) => value !== 'null' && value !== 'undefined');
    const responseName = responseTypeNameExceptions[method]
      ?? paramsTypes
        .map((name) => name.endsWith('Params') ? `${name.slice(0, -'Params'.length)}Response` : '')
        .find((name) => responseByName.has(name))
      ?? responseNameFromMethod(method, responseByName);

    if (!responseName || !responseByName.has(responseName)) {
      throw new Error(`No generated response type found for ${method} (${params}).`);
    }

    methods.push({ method, params, paramsTypes, responseName });
  }

  const imports = new Map();
  for (const entry of methods) {
    for (const typeName of [...entry.paramsTypes, entry.responseName]) {
      const generatedPath = importPaths.get(typeName) ?? responseByName.get(typeName);
      if (!generatedPath) {
        throw new Error(`No generated import found for ${typeName}.`);
      }
      const relativePath = normalizeImportPath(relative(protocolDir, generatedPath).replace(/\.ts$/, ''));
      const names = imports.get(relativePath) ?? [];
      names.push(typeName);
      imports.set(relativePath, names);
    }
  }

  const lines = ['// Generated by scripts/generate-codex-schema.mjs. Do not edit by hand.'];
  for (const [path, names] of [...imports.entries()].sort(([left], [right]) => left.localeCompare(right))) {
    lines.push(`import type { ${[...new Set(names)].sort().join(', ')} } from ${JSON.stringify(path)};`);
  }
  lines.push('', `export interface ${exportedName} {`);
  for (const entry of methods) {
    lines.push(`  ${JSON.stringify(entry.method)}: { params: ${entry.params}; result: ${entry.responseName} };`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

function parseImportPaths(source) {
  const imports = new Map();
  const pattern = /import type \{ ([^}]+) \} from "([^"]+)";/g;
  for (const match of source.matchAll(pattern)) {
    const typeName = match[1].trim();
    imports.set(typeName, resolve(dirname(join(generatedDir, basename(source))), `${match[2]}.ts`));
  }
  return imports;
}

function responseNameFromMethod(method, responseByName) {
  const pascal = method
    .split(/[\/_-]/)
    .filter(Boolean)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join('');
  const candidate = `${pascal}Response`;
  return responseByName.has(candidate) ? candidate : undefined;
}

function collectFiles(directory) {
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? collectFiles(path) : [path];
  });
}

function normalizeImportPath(path) {
  const normalized = path.split(sep).join('/');
  return normalized.startsWith('.') ? normalized : `./${normalized}`;
}
